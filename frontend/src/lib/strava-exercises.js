//   - LOWER_LEG (just TIBIALIS_RAISE) routes to CALF_RAISE_GENERIC — the only other lower-leg /
//     shin-and-calf category in the vocabulary.
//   - QUAD_EXTENSION routes to SQUAT_GENERIC — leg-extension work belongs to the quad/knee-extension
//     family, and Strava's own MACHINE_LEG_EXTENSION lives inside SQUAT, not its own category.
