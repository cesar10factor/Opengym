// matches, so each is routed to the neighbouring category whose movement pattern it is a variant
// of:
//   - HIP_THRUST routes to HIP_RAISE_GENERIC. Every HIP_THRUST identifier is functionally a hip
//     thrust variant, and Strava's own HIP_RAISE category already holds BARBELL_HIP_THRUST,
